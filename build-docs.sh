#!/usr/bin/env bash
# build-docs.sh: build the browsable DocFX documentation site locally.
#
# It generates API reference from the InductorParser XML doc comments,
# folds in the curated docs/ markdown and the readme (as the home page),
# and writes a static site to docs/docfx/_site.
#
# Usage:
#   ./build-docs.sh            # build once, output in docs/docfx/_site
#   ./build-docs.sh --serve    # build, then serve at http://localhost:8080
#
# A successful build leaves the site in docs/docfx/_site. The live site is deployed
# by the GitHub Actions workflow (.github/workflows/docs.yml) on push to master.
# Run this script for local preview. The workflow runs the same build.

set -euo pipefail

# Run from the repo root regardless of where the script is invoked.
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$repo_root"

# WSL has no native `dotnet` but can call the Windows SDK via interop.
# Fall back to dotnet.exe when dotnet isn't on PATH. On Linux and Git Bash
# on Windows, `dotnet` is present and this stays "dotnet". Same pattern as
# test.sh.
dotnet_command=dotnet
if ! command -v dotnet >/dev/null 2>&1; then
    dotnet_command=dotnet.exe
fi

# Absolute GitHub blob base for rewriting links that point outside the docs
# set (into src/, E2ESamples/, ...) so they stay clickable on the published
# site. The repo can be private, so the site never hotlinks raw.githubusercontent
# content (that 404s for anonymous visitors); assets the site needs are bundled
# as DocFX resources instead (see the chart staging below).
blob_base="https://github.com/EricZinda/InductorCSParser/blob/master"

# The curated docs that belong on the public site. Everything else in docs/
# (BugSearchLog/, PotentialBugSources/, Archive/) is internal and stays out.
# The capitalized Primer3/Primer4 match the real filenames.
curated_docs=(
    primer1.md
    primer2.md
    primerFailure.md
    Primer3.md
    Primer4.md
    tutorial-peek.md
    InductorParserReference.md
    CodeArchitecture.md
    ErrorArchitecture.md
    TestArchitecture.md
    Terminology.md
    UnicodeGotchas.md
    UnicodeInternalsArchitecture.md
    MappingPositionsAfterNormalization.md
    HowIBuiltThis.md
)

# The docfx tool manifest lives in docs/docfx/.config so the docs tooling
# stays out of the repo root. dotnet finds a local tool manifest by walking
# up from the current directory, so every docfx command runs from docs/docfx
# in a subshell. Paths handed to it are relative to that folder, and the
# rest of this script keeps running from the repo root.
run_in_docfx_dir() {
    (
        cd docs/docfx
        "$dotnet_command" "$@"
    )
}

echo "=== Restoring DocFX (local tool) ==="
run_in_docfx_dir tool restore

echo "=== Staging curated docs into docs/docfx/docs ==="
# Copy the curated docs flat into docs/docfx/docs so their mutual links (all flat,
# e.g. [ref](InductorParserReference.md)) keep resolving and DocFX rewrites
# them to .html. Rewrite parent-relative links (../E2ESamples, ../src, ...)
# and links into the docs/ subfolders that aren't staged (Archive,
# BugSearchLog, PotentialBugSources) to absolute GitHub blob URLs, since
# those targets aren't part of the site.
rm -rf docs/docfx/docs
mkdir -p docs/docfx/docs
for doc in "${curated_docs[@]}"; do
    sed \
        -e "s#](\.\./#](${blob_base}/#g" \
        -e "s#](Archive/#](${blob_base}/docs/Archive/#g" \
        -e "s#](BugSearchLog/#](${blob_base}/docs/BugSearchLog/#g" \
        -e "s#](PotentialBugSources/#](${blob_base}/docs/PotentialBugSources/#g" \
        "docs/${doc}" > "docs/docfx/docs/${doc}"
done
# Images the curated docs embed with a plain relative path. docfx.json lists
# docs/**.png as a site resource, so a copy next to the staged markdown is
# all it takes.
cp docs/bugs_features_per_day.png docs/docfx/docs/

echo "=== Staging the benchmark chart into docs/docfx/images ==="
# The chart artifacts live under src/Benchmarks (regenerated by each benchmark
# run), outside the docs tree, so DocFX can't see them on its own. Copy them
# into docs/docfx/images, which docfx.json bundles as a site resource, so the home
# page can reference them with a relative path that works even when the repo is
# private. (docs/docfx/images is gitignored, like the other staged build outputs.)
rm -rf docs/docfx/images
mkdir -p docs/docfx/images
cp src/Benchmarks/performance-chart.jpg docs/docfx/images/
cp src/Benchmarks/performance-chart.html docs/docfx/images/

echo "=== Generating home page from readme.md ==="
# Use the readme as the site home so it stays the single source of truth.
# Prepend an H1 title (the readme opens with a paragraph, no heading of its
# own). The readme is also the NuGet package's readme, and nuget.org can't
# resolve relative links, so every link in it is already an absolute URL:
# docs pages point at the published site, the benchmark chart and its
# interactive HTML at the site's images/ copies (staged above), and
# everything else at GitHub. Nothing needs rewriting here.
{
    printf '# The Inductor Parser\n\n'
    cat readme.md
} > docs/docfx/index.md

echo "=== Cleaning previous output ==="
# DocFX doesn't delete stale files from a prior run, so wipe the generated API
# metadata and the rendered site before rebuilding. Without this, a doc or type
# removed from the inputs would linger in _site and get published.
rm -rf docs/docfx/api docs/docfx/_site

echo "=== Generating API metadata ==="
run_in_docfx_dir docfx metadata docfx.json

echo "=== Building the categorized API sidebar ==="
# The metadata step writes docs/docfx/api/toc.yml grouped by namespace, with every
# type entry indented two spaces ("  - uid:") and namespace entries at column 0.
# We replace it with a sidebar that groups every public type into task-based
# sections instead. There's no separate API index page: the top navigation's
# API entry (docs/docfx/toc.yml) lands on the Rules class with this sidebar
# next to it, and the sidebar is the categorized overview.
api_dir="docs/docfx/api"
all_type_uids=$(grep -E '^  - uid: ' "$api_dir/toc.yml" | sed -E 's/^  - uid: //')

# Editorial grouping for the API sidebar. Lines starting with "# " are section
# headings; every other non-blank line is a type uid placed under the current
# heading, in this order. This is the one hand-maintained list in the docs, so
# the completeness check below appends (and warns about) any public type that's
# missing rather than letting a newly added type silently drop off the sidebar.
api_sidebar_layout='# Building a Grammar
InductorParser.Rules
InductorParser.TokenSet
InductorParser.TokenSet.Ascii
InductorParser.LateBoundRule
InductorParser.SyntaxTree.FlattenType
# Starting a Parse
InductorParser.ParseOptions
InductorParser.ParseCancellation
InductorParser.Tracing.TraceLevel
# Parse Results
InductorParser.ParseResult
InductorParser.ParseOutcome
InductorParser.SyntaxTree.SourcePosition
InductorParser.SyntaxTree.SourceRange
InductorParser.SyntaxTree.Symbol
InductorParser.SyntaxTree.SymbolId
InductorParser.SyntaxTree.ParseContext
# Writing a Rule
InductorParser.Rule
InductorParser.Lexing.Lexer
InductorParser.Lexing.Token
InductorParser.Lexing.Lexer.Probe
InductorParser.Lexing.Lexer.Transaction
InductorParser.INormalizationReporter
InductorParser.Invariant
InductorParser.InductorParserBugException
# Unicode
InductorParser.Lexing.UnicodeEnvironment
InductorParser.Lexing.UnicodeImplementation
InductorParser.Lexing.GraphemeHelpers
InductorParser.Lexing.NormalizationHelpers
InductorParser.Lexing.RuneHelpers
# Infrastructure
InductorParser.SyntaxTree.SymbolRanges
InductorParser.InvariantInterpolatedStringHandler
InductorParser.Tracing.TraceInterpolatedStringHandler'

# Completeness check: warn (don't silently drop) if a public type is missing
# from the layout, or if the layout names a type that no longer exists.
layout_uids=$(printf '%s\n' "$api_sidebar_layout" | grep -Ev '^(#|$)')
missing=$(comm -23 <(printf '%s\n' "$all_type_uids" | sort -u) <(printf '%s\n' "$layout_uids" | sort -u))
stale=$(comm -13 <(printf '%s\n' "$all_type_uids" | sort -u) <(printf '%s\n' "$layout_uids" | sort -u))
if [ -n "$missing" ]; then
    echo "WARNING: public types missing from the API sidebar layout (appended under Uncategorized):" >&2
    printf '  %s\n' $missing >&2
fi
if [ -n "$stale" ]; then
    echo "WARNING: API sidebar layout names types that no longer exist:" >&2
    printf '  %s\n' $stale >&2
fi

# Sidebar grouped into the task-based sections above. Each "# Heading" becomes
# a collapsible group. Each uid becomes a type link under it.
{
    printf '### YamlMime:TableOfContent\n'
    printf 'items:\n'
    while IFS= read -r line; do
        case "$line" in
            '# '*) printf -- '- name: %s\n  items:\n' "${line#\# }" ;;
            '')    ;;
            *)     printf -- '  - uid: %s\n' "$line" ;;
        esac
    done <<< "$api_sidebar_layout"
    # Keep the sidebar complete: any type missing from the layout (already
    # warned about above) goes under its own group rather than vanishing.
    if [ -n "$missing" ]; then
        printf -- '- name: Uncategorized\n  items:\n'
        for uid in $missing; do printf -- '  - uid: %s\n' "$uid"; done
    fi
} > "$api_dir/toc.yml"

echo "=== Building the site ==="
# DocFX prints "Invalid file link" warnings for any broken cross-reference.
# Scan the output for those after a build to keep the site link-clean.
run_in_docfx_dir docfx build docfx.json

if [ "${1:-}" = "--serve" ]; then
    echo "=== Serving at http://localhost:8080 (Ctrl+C to stop) ==="
    run_in_docfx_dir docfx serve _site
fi
